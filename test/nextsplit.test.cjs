const fs=require('fs'),vm=require('vm'),assert=require('assert');
const code=fs.readFileSync(__dirname+'/../krohnkite.js','utf8');
vm.runInThisContext(code);
const area=new Rect(32,56,1200,800), gap=32;
const tile=(id,g)=>({id,geometry:g,state:WindowState.Tiled});
const A=tile('A',new Rect(32,56,584,800));
const B=tile('B',new Rect(648,56,584,800));
const C=tile('C',new Rect(0,0,100,100));
const state=new NextSplitState();let ctx={currentWindow:A};
state.remember([A,B],area,gap);
const before=JSON.stringify([A.geometry,B.geometry]);
state.request('A','y');
assert.equal(JSON.stringify([A.geometry,B.geometry]),before,'arming must not move windows');
state.created('C');state.apply(ctx,[A,B,C],area,gap);
assert.deepEqual(B.geometry,new Rect(648,56,584,800),'unrelated B must not move');
assert.equal(C.geometry.y,A.geometry.y+A.geometry.height+gap);
assert.equal(C.geometry.x,A.geometry.x);
const split=JSON.stringify([A.geometry,B.geometry,C.geometry]);
state.apply(ctx,[A,B],area,gap);assert.equal(A.geometry.height,800);
state.apply(ctx,[A,B,C],area,gap);assert.equal(JSON.stringify([A.geometry,B.geometry,C.geometry]),split,'restore minimized leaf');
const oldHeight=A.geometry.height;
state.adjust(area,[A,B,C],A,new RectDelta(0,0,40,0),gap);
state.apply(ctx,[A,B,C],area,gap);assert.equal(A.geometry.height,oldHeight+40);
const oldA=A.geometry,oldC=C.geometry;
state.apply(ctx,[C,B,A],area,gap);assert.deepEqual(A.geometry,oldC);assert.deepEqual(C.geometry,oldA);
const D=tile('D',new Rect(0,0,100,100));
state.request('C','x');state.created('D');state.apply(ctx,[C,B,A,D],area,gap);
assert.equal(D.geometry.x,C.geometry.x+C.geometry.width+gap);
assert.equal(D.geometry.y,C.geometry.y);
state.remove('D');state.apply(ctx,[C,B,A],area,gap);
assert.deepEqual(C.geometry,oldA,'close new leaf restores parent');
console.log('PASS: deferred insertion, local geometry, restore, resize, swaps, both axes, close');
